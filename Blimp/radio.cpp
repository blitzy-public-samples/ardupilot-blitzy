/**
 * @file radio.cpp
 * @brief RC radio input processing for Blimp vehicle
 * 
 * @details This file implements RC radio input handling for the Blimp lighter-than-air
 *          vehicle, including:
 *          - RC channel initialization and binding (right/front/up/yaw control)
 *          - Input deadzone configuration to filter stick jitter
 *          - Throttle-zero detection with debouncing to identify pilot shutdown intent
 *          - Radio failsafe detection and counter-based triggering
 *          - Pilot input validation and timeout handling
 *          
 *          The radio failsafe system is safety-critical: it protects against loss of
 *          RC signal by counting consecutive low-throttle frames (FS_COUNTER = 3) or
 *          detecting timeout periods (500ms normal, 2000ms with RC_OVERRIDE). When
 *          triggered, the failsafe engages protective actions defined elsewhere in the
 *          flight controller.
 *          
 *          Coordinate system: Uses Blimp body frame (right/front/up/yaw)
 *          Update rate: Called at main loop rate (typically 50Hz for blimp)
 *          
 * @note This module processes raw RC input but does not directly control motors.
 *       Motor commands are generated by control loops using the validated RC inputs.
 * 
 * @warning Radio failsafe is a safety-critical system. Any modifications must be
 *          thoroughly tested to ensure proper failsafe triggering and disengagement.
 */

#include "Blimp.h"


// Function that will read the radio data, limit servos and trigger a failsafe
